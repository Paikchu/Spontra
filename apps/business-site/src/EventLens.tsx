import { Button } from "@/packages/web/src/ui/button";
import { useMemo, useState, type CSSProperties } from "react";
import type { CompanyEvent, EventsPublication } from "@/shared/analysis-contract/events";
import { INSIDER_RULES } from "@/shared/analysis-runtime/events";
import { EVENT_CLASS_LABEL, dollars, eventTitle, insiderLens, shares, shortDate, type InsiderLensModel } from "./events-model";

const ITEM_LABEL: Record<string, string> = {
  "1.01": "Material agreement", "1.02": "Agreement terminated", "1.05": "Cybersecurity incident", "2.01": "Acquisition or disposition completed", "2.02": "Results of operations", "2.03": "New financial obligation", "2.04": "Acceleration triggered", "2.05": "Exit costs",
  "2.06": "Material impairment", "3.01": "Delisting notice", "3.02": "Unregistered equity sale", "3.03": "Rights of holders modified", "4.01": "Auditor change", "4.02": "Non-reliance on financials", "5.01": "Change in control", "5.02": "Director or officer change",
  "5.03": "Bylaw amendment", "5.07": "Shareholder vote results", "7.01": "Reg FD disclosure", "8.01": "Other events", "9.01": "Exhibits",
};

/**
 * The event in focus, in the lens's place: its figures or chart on the left, what it says and
 * where it was filed on the right. Nothing here is written by a model except the filing's own
 * summary, which is labelled as such; the verdict on an insider sale is a rule, shown with its rule.
 */
export function EventLens({ event, publication, onClose, onStep, index, count }: {
  event: CompanyEvent;
  publication: EventsPublication;
  onClose: () => void;
  onStep: (delta: 1 | -1) => void;
  index: number;
  count: number;
}) {
  const insider = useMemo(() => insiderLens(publication, event), [publication, event]);
  const [showQuiet, setShowQuiet] = useState(false);
  return <section className="lens event-lens" data-class={event.class} aria-label={`Event: ${eventTitle(event)}`} key={event.id}>
    <header className="lens-head">
      <div className="lens-title">
        <b className="lens-kind event-kind">{EVENT_CLASS_LABEL[event.class]}</b>
        <h2>{eventTitle(event)}</h2>
        <span className="lens-basis">{event.form} · Filed {event.filedAt}{event.eventDate !== event.filedAt ? ` · Event ${event.eventDate}` : ""}</span>
      </div>
      <div className="lens-nav">
        <span className="lens-steps"><Button variant="unstyled" type="button" aria-label="Newer event" disabled={index <= 0} onClick={() => onStep(-1)}>‹</Button><span>{index + 1} / {count}</span><Button variant="unstyled" type="button" aria-label="Older event" disabled={index >= count - 1} onClick={() => onStep(1)}>›</Button></span>
        <Button variant="unstyled" type="button" className="lens-close" aria-label="Close event" onClick={onClose}>✕</Button>
      </div>
    </header>
    <div className="lens-body">
      <div className="lens-chart">
        {insider ? <InsiderLadder model={insider} event={event} /> : <Facts event={event} />}
      </div>
      <div className="lens-text">
        {insider && <InsiderReading model={insider} event={event} />}
        {event.summary ? <>
          <p className="lens-judgment">{event.summary.headline}</p>
          <ul className="event-bullets">{event.summary.bullets.map((b, i) => <li key={i} data-importance={b.importance}><b>{b.label}</b>{b.detail}</li>)}</ul>
          {event.summary.analystView && <p className="event-view"><b>What it means for investors</b>{event.summary.analystView}</p>}
          <p className="event-generated">Summary generated by a model on {event.summary.generatedAt.slice(0, 10)}; the filing’s figures prevail</p>
        </> : !insider && <p className="lens-empty">No summary for this filing yet. The class comes from the 8-K item numbers; see the filing for details.</p>}
        {insider && insider.path.length > 0 && event.insider!.footnotes.length > 0 && <details className="event-footnotes" open={showQuiet} onToggle={e => setShowQuiet((e.target as HTMLDetailsElement).open)}>
          <summary>{event.insider!.footnotes.length} filing {event.insider!.footnotes.length === 1 ? "footnote" : "footnotes"}</summary>
          <ol>{event.insider!.footnotes.map((f, i) => <li key={i}>{f}</li>)}</ol>
        </details>}
        <ol className="sources sources--numbered">
          <li><a href={event.edgarUrl} target="_blank" rel="noopener noreferrer">EDGAR filing index<span aria-hidden="true"> ↗</span></a></li>
          <li><a href={event.documentUrl} target="_blank" rel="noopener noreferrer">{event.form} filing<span aria-hidden="true"> ↗</span></a></li>
          {event.exhibits.map(x => <li key={x.url}><a href={x.url} target="_blank" rel="noopener noreferrer">{x.type} · {x.title}<span aria-hidden="true"> ↗</span></a></li>)}
        </ol>
      </div>
    </div>
  </section>;
}

/** A current report's facts: the item codes it was filed under, in words, and what the primary document is. */
function Facts({ event }: { event: CompanyEvent }) {
  return <dl className="event-facts">
    <div><dt>Form</dt><dd>{event.form}</dd></div>
    <div><dt>Event date</dt><dd>{event.eventDate}</dd></div>
    {event.items.length > 0 && <div><dt>Items</dt><dd>{event.items.map(i => <span key={i} className="event-item">Item {i}<small>{ITEM_LABEL[i] ?? ""}</small></span>)}</dd></div>}
    {event.description && <div><dt>Document</dt><dd>{event.description}</dd></div>}
    {event.exhibits.length > 0 && <div><dt>Exhibits</dt><dd>{event.exhibits.map(x => x.type).join(", ")}</dd></div>}
    {event.summary?.eventCategory && <div><dt>Summary category</dt><dd>{event.summary.eventCategory}</dd></div>}
  </dl>;
}

/** The reading of one Form 4 against the owner's own history and the other insiders, with the rule that decided it. */
function InsiderReading({ model, event }: { model: InsiderLensModel; event: CompanyEvent }) {
  const t = event.insider!;
  const role = [t.title, t.isDirector ? "Director" : null, t.isTenPercentOwner ? "10% owner" : null].filter(Boolean).join(" · ") || "Filer";
  return <>
    <p className="lens-judgment event-verdict" data-verdict={model.tone}>
      <b>{model.verdict.label}</b>{t.ownerName} ({role}) {t.sold ? `sold ${shares(t.sold.shares)} at an average $${t.sold.averagePrice.toFixed(2)}, ${dollars(t.sold.proceeds)} in total` : t.bought ? `bought ${shares(t.bought.shares)}, ${dollars(t.bought.cost)} in total` : t.exercised ? `exercised ${shares(t.exercised)} and sold none` : "had a holding change with no trade"}.
    </p>
    <ul className="event-rules">{model.verdict.rules.map((r, i) => <li key={i}>{r}</li>)}</ul>
    <dl className="lens-evidence">
      {t.sold && <div className="lens-row"><dt>Share of prior holding</dt><dd><b>{model.share != null ? `${model.share.toFixed(1)}%` : "—"}</b><em>Threshold {INSIDER_RULES.attentionShare}%</em></dd></div>}
      <div className="lens-row"><dt>Direct holding after</dt><dd><b>{t.heldAfter != null ? shares(t.heldAfter) : "Not disclosed"}</b></dd></div>
      <div className="lens-row"><dt>10b5-1 plan</dt><dd><b>{t.rule10b51 === true ? "Yes" : t.rule10b51 === false ? "No" : "Not marked on the form"}</b>{t.planAdoptedOn && <em>Adopted {t.planAdoptedOn}</em>}</dd></div>
      <div className="lens-row"><dt>Sales, last 12 months</dt><dd><b>{model.cadence.sales.length} {model.cadence.sales.length === 1 ? "sale" : "sales"} · {shares(model.cadence.totalShares)}</b><em>{model.cadence.intervalDays != null ? `About ${Math.round(model.cadence.intervalDays)} days apart${model.cadence.regular ? " · Steady cadence" : ""}` : "No comparable interval"} · {dollars(model.cadence.totalProceeds)} in total</em></dd></div>
      <div className="lens-row"><dt>Other insiders selling</dt><dd><b>{model.cluster.length} {model.cluster.length === 1 ? "person" : "people"}</b><em>Within {INSIDER_RULES.clusterDays} days</em></dd></div>
    </dl>
    {model.cluster.length > 0 && <ul className="event-cluster">{model.cluster.map(c => <li key={c.id}><span>{c.ownerName}{c.title ? ` · ${c.title}` : ""}</span><span>{shortDate(c.date)} · {dollars(c.proceeds)}</span></li>)}</ul>}
  </>;
}

/**
 * The owner's holding over the trailing two years as a staircase: each filing's held-after figure
 * is a step, a sale drops it, an exercise or purchase lifts it. Dots mark sales, sized by proceeds,
 * hollow when the filing says the trade ran under a 10b5-1 plan. The focused filing is lit.
 */
function InsiderLadder({ model, event }: { model: InsiderLensModel; event: CompanyEvent }) {
  const path = model.path;
  if (path.length < 2) return <div className="lens-empty">{event.insider!.ownerName} has only this filing in the window, so no holding path can be drawn.<br />{event.insider!.heldAfter != null ? `Holding after the trade: ${shares(event.insider!.heldAfter)}` : ""}</div>;
  const held = path.map(p => p.held);
  // A large holder's sales are small against the holding, so the scale hugs the path rather than starting at zero.
  const peak = Math.max(...held, ...path.map(p => p.held + p.sold)), low = Math.min(...held);
  const top = peak + (peak - low) * 0.08, bottom = Math.max(0, low - (peak - low) * 0.15);
  const range = top - bottom || 1;
  const t0 = Date.parse(path[0].date), t1 = Date.parse(path[path.length - 1].date);
  const span = Math.max(t1 - t0, 30 * 86_400_000);
  const x = (d: string) => 4 + (Date.parse(d) - t0) / span * 92;
  const y = (v: number) => 92 - (v - bottom) / range * 84;
  // The staircase: hold flat from each filing to the next, then step to the new level.
  const d = path.map((p, i) => `${i ? "L" : "M"}${x(p.date).toFixed(2)},${y(i ? path[i - 1].held : p.held + p.sold - p.bought - p.exercised).toFixed(2)}L${x(p.date).toFixed(2)},${y(p.held).toFixed(2)}`).join("") + `L96,${y(path[path.length - 1].held).toFixed(2)}`;
  const maxProceeds = Math.max(1, ...model.cadence.sales.map(s => s.proceeds), ...path.map(p => p.sold * (event.insider!.sold?.averagePrice ?? 0)));
  const sales = path.filter(p => p.sold > 0);
  return <div className="insider-ladder" role="img" aria-label={`${event.insider!.ownerName} holding path, ${path[0].date} to ${path[path.length - 1].date}, ${sales.length} ${sales.length === 1 ? "sale" : "sales"}`}>
    <div className="lens-legend"><span><i className="ladder-step" />Direct holding</span><span><i className="ladder-dot" />Sale (area = amount)</span><span><i className="ladder-dot ladder-dot--planned" />10b5-1 plan</span></div>
    <svg viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true">
      {[0.25, 0.5, 0.75].map(t => <line key={t} className="ladder-grid" x1="4" x2="96" y1={8 + t * 84} y2={8 + t * 84} vectorEffect="non-scaling-stroke" />)}
      <path className="ladder-path" d={d} vectorEffect="non-scaling-stroke" />
    </svg>
    <div className="ladder-marks">
      {sales.map(p => {
        const proceeds = model.cadence.sales.find(s => s.id === p.id)?.proceeds ?? 0;
        const size = 8 + Math.sqrt(Math.max(proceeds, 1) / maxProceeds) * 18;
        return <i key={p.id} className="ladder-dot" data-planned={p.planned === true || undefined} data-focus={p.id === event.id || undefined}
          style={{ left: `${x(p.date)}%`, top: `${y(p.held)}%`, width: size, height: size } as CSSProperties} title={`${p.date} sold ${shares(p.sold)} · ${dollars(proceeds)}`} />;
      })}
    </div>
    <div className="lens-axis"><span style={{ left: "4%" }} data-edge="start">{path[0].date.slice(0, 7).replace("-", ".")}</span><span style={{ left: "96%" }} data-edge="end">{path[path.length - 1].date.slice(0, 7).replace("-", ".")}</span></div>
    <div className="ladder-scale"><span>{shares(top)}</span><span>{shares(bottom)}</span></div>
  </div>;
}
